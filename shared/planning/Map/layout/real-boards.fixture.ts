import type { MapItemRow, MapItemStatus, MapItemSubStatus, MapItemType } from '@specboard/core/map-read';

/**
 * The structure of two real boards as the design pass staged them, anonymized: keys are a neutral prefix and
 * the original number, titles are dropped, and times are days before the capture. What is kept is what the
 * layout reads: types, statuses, parents, ranks, when each item was filed and last had an event, which items
 * were discovered from which, and the open blockers. Done items carry no completion stamp, since the boards
 * predate the stamps, so each anchors on its latest event.
 *
 * Row: number, type (e, t, b), status, sub-status, parent number, filed and latest event (days before the
 * capture), rank, discovered-from number, has a PR, has an origin.
 */
type Row = [number, string, MapItemStatus, MapItemSubStatus | null, number | null, number, number, number, number | null, number, number];

export interface RealBoard {
	now: number;
	rows: MapItemRow[];
}

const TYPES: Record<string, MapItemType> = { e: 'epic', t: 'task', b: 'bug' };

function build(prefix: string, capture: string, rows: Row[], blockers: Array<[number, number, number]>): RealBoard {
	const now = Date.parse(capture);
	const at = (days: number): string => new Date(now - days * 86_400_000).toISOString();
	const key = (n: number): string => `${prefix}-${n}`;
	const built: MapItemRow[] = rows.map(([n, type, status, subStatus, parent, filed, event, rank, discovered, pr, origin]) => ({
		key: key(n),
		type: TYPES[type]!,
		title: `Item ${n}`,
		status,
		subStatus,
		blocked: false,
		parentKey: parent === null ? null : key(parent),
		rank,
		createdAt: at(filed),
		startedAt: status === 'in_progress' || status === 'in_review' ? at(event) : null,
		completedAt: null,
		timeAnchor: at(event),
		workers: [],
		blockers: [],
		textBlockerCount: 0,
		discoveredFromKey: discovered === null ? null : key(discovered),
		originActorType: origin ? 'agent' : null,
		prUrl: pr ? 'https://example.test/pr' : null,
		specCount: 0,
	}));
	const byKey = new Map(built.map((row) => [row.key, row]));
	for (const [blocked, blocker, cleared] of blockers) {
		const row = byKey.get(key(blocked))!;
		if (cleared) row.blockers.push({ blockerKey: key(blocker), state: 'satisfied', satisfiedAt: row.timeAnchor });
		else {
			row.blockers.push({ blockerKey: key(blocker), state: 'open' });
			row.blocked = true;
		}
	}
	return { now, rows: built };
}

